CAMPAIGN = 'thermal_refresh_2026_v1'
DOMAINS = {'yampa': 32, 'b120': 32, 'ucrb': 64}
PARENTS = {'b120': 'cnrfc', 'yampa': 'ucrb', 'ucrb': 'conus', 'cnrfc': 'conus'}
PUBLICATION = 'forcing/work/temperature-refresh/campaign-20261109T055015Z/publication/acceptance.json'


def interval(stream, domain=None):
    if domain == 'cnrfc':
        if stream != 'nrt':
            raise ValueError('CNRFC uses its existing Retro continuation')
        return datetime(2026, 4, 17), datetime(2026, 11, 11)
    if stream == 'retro':
        return datetime(2026, 2, 1), datetime(2026, 4, 18)
    if stream == 'nrt':
        return datetime(2026, 4, 18), datetime(2026, 11, 8)
    raise ValueError('Unknown stream')


def load(path):
    return json.loads(path.read_text())


def validate_predecessor(record, domain, plan_hash):
    if (record.get('status') != 'complete' or record.get('domain') != domain
            or record.get('stream') != 'retro' or record.get('end') != str(interval('nrt', domain)[0])
            or record.get('plan_sha256') != plan_hash):
        raise ValueError('Refreshed Retro predecessor must pass for this domain and plan')


def superseded_checkpoints(root, staged, start, end):
    """Find old interior checkpoints not regenerated by the refreshed run."""
    result = []
    for path in sorted(root.glob('*/*/RESTART.*_DOMAIN1')):
        stamp = datetime.strptime(path.name,'RESTART.%Y%m%d%H_DOMAIN1')
        if not start < stamp <= end:
            continue
        pair = [path.parent/n for n in restart_names(stamp)]
        generated = [staged/stamp.strftime('%Y/%m')/n for n in restart_names(stamp)]
        if all(p.exists() for p in generated):
            continue
        if any(p.exists() for p in generated) or not all(p.exists() for p in pair):
            raise ValueError('Unpaired superseded checkpoint')
        result.extend(pair)
    return result


def audit_lineage(root, domain, stream, start, end):
    """Check the whole current subset chain, including untouched source days."""
    pins = {}
    day = start
    while day <= end:
        child = domain
        while child != 'conus':
            path = root/f'forcing/outputs/{child}/{stream}/hourly'/day.strftime('%Y/%m/%Y%m%d.LDASIN_DOMAIN1')
            source = root/f'forcing/outputs/{PARENTS[child]}/{stream}/hourly'/day.strftime('%Y/%m/%Y%m%d.LDASIN_DOMAIN1')
            receipt = load(path.with_name(path.name+'.subset.json'))
            if (receipt.get('status') != 'passed' or receipt.get('missing_active_values') != 0
                    or receipt.get('retained_values_exact_match') is not True
                    or receipt.get('output_identity') != file_identity(path)
                    or receipt.get('source_identity') != file_identity(source)
                    or Path(receipt['source']).resolve() != source.resolve()):
                raise ValueError(f'Stale subset lineage: {path}')
            pins[str(path)] = file_identity(path)
            pins[str(source)] = file_identity(source)
            child = PARENTS[child]
        day += timedelta(days=1)
    return pins


def submit(root, state):
    state.mkdir(parents=True, exist_ok=True)
    with (state/'submission.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        if (state/'plan.json').exists() or (state/'submission.json').exists():
            raise ValueError('Existing campaign; inspect before retry')
        jobs = subprocess.check_output(['squeue','--me','-h','-o','%j'], text=True)
        if any(f'wrfh-{d}-' in jobs for d in DOMAINS):
            raise ValueError('A target-domain model job is already queued or running')
        publication = load(root/PUBLICATION)
        if publication.get('status') != 'passed' or publication.get('job') != '5232861':
            raise ValueError('Forcing publication must pass')
        plan = {'authorized': True, 'campaign': CAMPAIGN, 'publication_sha256': digest(root/PUBLICATION),
                'publication': PUBLICATION, 'domains': {}, 'cron_changed': False}
        for domain, ranks in DOMAINS.items():
            initial = root/f'nwm/restarts/{domain}/retro/2026/02'
            pair = {str(initial/n): file_identity(initial/n) for n in restart_names(interval('retro')[0])}
            mask = root/f'nwm/static/domains/{domain}/masks/{domain}_masks.nc'
            gate = root/f'nwm/outputs/{domain}/tests/repaired-retro-start-{GATES[domain]}/acceptance.json'
            old = load(gate)
            if old.get('status') != 'passed' or old.get('restart_equivalence') != 'passed':
                raise ValueError('Existing corrected-start gate did not pass')
            for stream in ('retro','nrt'):
                start, end = interval(stream)
                day = start
                while day <= end:
                    path = root/f'forcing/outputs/{domain}/{stream}/hourly'/day.strftime('%Y/%m/%Y%m%d.LDASIN_DOMAIN1')
                    if not path.is_file():
                        raise FileNotFoundError(path)
                    day += timedelta(days=1)
                with Dataset(path) as ds:
                    t = ds['time']
                    stamps = num2date(t[:],t.units,only_use_cftime_datetimes=False)
                    if end not in stamps:
                        raise ValueError('Missing midnight endpoint')
            plan['domains'][domain] = {'ranks': ranks, 'initial_pins': pair,
                'mask': str(mask), 'mask_sha256': digest(mask), 'startup_gate': str(gate),
                'startup_gate_sha256': digest(gate)}
        write_json(state/'plan.json',plan)
        journal = {'status':'submitting','jobs':[]}
        write_json(state/'submission.json',journal)
        for domain,ranks in DOMAINS.items():
            previous = None
            for stage in ('retro','nrt'):
                start,end = interval(stage)
                cmd = ['sbatch','--parsable',f'--ntasks={ranks}',
                       f'--job-name=wrfh-{domain}-thermal-{stage}-{start:%Y%m%d}-{end:%Y%m%d}-{ranks}r']
                if previous:
                    cmd += [f'--dependency=afterok:{previous}']
                cmd += ['slurm/refresh_thermal_model_2026.sh','--stage',stage,'--domain',domain]
                entry = {'command':cmd,'domain':domain,'stage':stage,'status':'submission_uncertain'}
                journal['jobs'].append(entry)
                write_json(state/'submission.json',journal)
                previous = subprocess.check_output(cmd,cwd=root,text=True).strip().split(';')[0]
                if not previous.isdecimal():
                    raise ValueError('Invalid sbatch response')
                entry.update(status='submitted',job=previous)
                write_json(state/'submission.json',journal)
        journal['status'] = 'submitted'
        write_json(state/'submission.json',journal)
        print(json.dumps(journal),flush=True)


def execute(root, state, domain, stream):
    plan = load(state/'plan.json')
    spec = plan['domains'][domain]
    plan_hash = digest(state/'plan.json')
    start,end = interval(stream, domain)
    work = state/domain/stream
    work.mkdir(parents=True,exist_ok=False)
    report = {'status':'running','domain':domain,'stream':stream,'start':str(start),'end':str(end),
              'plan_sha256':plan_hash,'job':os.environ['SLURM_JOB_ID']}
    try:
        if not plan.get('authorized') or plan.get('campaign') != CAMPAIGN:
            raise ValueError('Unauthorized campaign')
        if int(os.environ['SLURM_NTASKS']) != spec['ranks']:
            raise ValueError('MPI rank allocation mismatch')
        if digest(root/PUBLICATION) != plan['publication_sha256']:
            raise ValueError('Forcing publication report changed')
        if digest(Path(spec['mask'])) != spec['mask_sha256'] or digest(Path(spec['startup_gate'])) != spec['startup_gate_sha256']:
            raise ValueError('Domain/startup evidence changed')
        domain_root = root/'nwm/static/domains'/domain
        check_parameters(domain_root)
        with ExitStack() as stack:
            locks = [root/f'nwm/runs/{domain}/{stream}/production.lock']
            if stream == 'retro':
                locks += [root/f'nwm/runs/{domain}/retro/repaired_rain_retro_v1/production.lock']
            for path in locks:
                path.parent.mkdir(parents=True,exist_ok=True)
                lock = stack.enter_context(path.open('a'))
                fcntl.flock(lock,fcntl.LOCK_EX | fcntl.LOCK_NB)
            pins = spec['initial_pins']
            if stream == 'nrt':
                predecessor = load(state/domain/'retro/acceptance.json')
                validate_predecessor(predecessor,domain,plan_hash)
                pins = predecessor['terminal_restart_pins']
            initial = work/'initialization'
            initial.mkdir()
            for source,pin in pins.items():
                if file_identity(Path(source)) != pin:
                    raise ValueError('Initial checkpoint changed')
                os.link(source,initial/Path(source).name)
            restart_check([initial/n for n in restart_names(start)],start)
            lineage = audit_lineage(root,domain,stream,start,end)
            write_json(work/'forcing-lineage.json',{'status':'passed','identities':lineage})
            frozen = work/'forcing'
            snapshot_forcing(root/f'forcing/outputs/{domain}/{stream}/hourly',frozen,start,end)
            scratch = Path(f'/scratch/{os.environ["SLURM_JOB_USER"]}/job_{os.environ["SLURM_JOB_ID"]}')
            stop = start+timedelta(days=2)
            continuous = integration(root,domain_root,frozen,start,stop,work/'test/continuous',scratch/'test-continuous',initial)
            resumed = integration(root,domain_root,frozen,start+timedelta(days=1),stop,
                work/'test/resumed',scratch/'test-resumed',work/'test/continuous/restarts'/(start+timedelta(days=1)).strftime('%Y/%m'))
            differences = {}
            for name in restart_names(stop):
                fields = ('SMC','SH2O','SOIL_T','SNEQV') if name.startswith('RESTART') else ('hlink','qlink1','qlink2','z_gwsubbas')
                with Dataset(work/'test/continuous/restarts'/stop.strftime('%Y/%m')/name) as a, \
                        Dataset(work/'test/resumed/restarts'/stop.strftime('%Y/%m')/name) as b:
                    for field in fields:
                        x,y = np.ma.asarray(a[field][:]),np.ma.asarray(b[field][:])
                        np.testing.assert_array_equal(np.ma.getmaskarray(x),np.ma.getmaskarray(y))
                        np.testing.assert_allclose(x.compressed(),y.compressed(),rtol=1e-5,atol=1e-6)
                        differences[field] = float(np.ma.max(np.ma.abs(x.astype('f8')-y.astype('f8'))))
            gate = report | {'status':'passed','restart_equivalence':'passed',
                'forcing_publication_job':'5232861','max_abs_differences':differences,
                'all_archived_records_verified':continuous['all_archived_records_verified'] and resumed['all_archived_records_verified'],
                'midnight_merge_tested':True,'archive_policy':'explicit_record_stack_v1'}
            write_json(work/'gate.json',gate)
            run(root,2026,campaign=CAMPAIGN,archive_gate=work/'gate.json',stream=stream,domain=domain,
                start_date=str(start.date()),end_date=str(end.date()),initial_restart_dir=initial,
                forcing_root=frozen,refresh_workspace=work,stream_lock=lock)
            completion = load(work/'runs/2026'/f'{start:%Y%m%d}-{end:%Y%m%d}-passed.json')
            if not completion.get('passed') or completion.get('end') != str(end):
                raise ValueError('Model completion not accepted')
            if any(file_identity(Path(p)) != pin for p,pin in lineage.items()):
                raise ValueError('Source forcing changed; do not publish stale run')
            pairs = prepare_publication(work,root/f'nwm/outputs/{domain}/{stream}',root/f'nwm/restarts/{domain}/{stream}')
            restart_root = root/f'nwm/restarts/{domain}/{stream}'
            obsolete = superseded_checkpoints(restart_root,work/'restarts',start,end)
            retirement = {'status':'planned','files':[{ 'source':str(p), 'identity':file_identity(p),
                'backup':str(work/'publication/superseded-restarts'/p.relative_to(restart_root))} for p in obsolete]}
            write_json(work/'publication/superseded-checkpoints.json',retirement)
            canonical = root/f'nwm/restarts/{domain}/{stream}'/end.strftime('%Y/%m')
            report['terminal_restart_pins'] = {str(canonical/n):file_identity(work/'restarts'/end.strftime('%Y/%m')/n) for n in restart_names(end)}
            if stream == 'nrt':
                latest = work/'latest.json'
                write_json(latest,report | {'status':'complete','campaign':CAMPAIGN,'acceptance':str(work/'acceptance.json')})
                pairs.append((latest,root/f'nwm/status/{domain}/nrt-daily/latest.json'))
            transaction = publish_transaction(pairs,work/'publication/transaction.json')
            if transaction['status'] != 'complete':
                raise ValueError('Publication incomplete')
            for row in retirement['files']:
                source,backup = Path(row['source']),Path(row['backup'])
                if file_identity(source) != row['identity'] or backup.exists():
                    raise ValueError('Superseded checkpoint changed')
                backup.parent.mkdir(parents=True,exist_ok=True)
                source.rename(backup)
            retirement['status'] = 'complete'
            write_json(work/'publication/superseded-checkpoints.json',retirement)
            restart_check([canonical/n for n in restart_names(end)],end)
            report.update(status='complete',published_files=len(pairs),restart_frequency='monthly plus terminal',
                          previous_files_retained=True,superseded_checkpoint_files=len(obsolete),cron_changed=False)
    except BaseException as error:
        report.update(status='failed',error=str(error))
        raise
    finally:
        write_json(work/'acceptance.json',report)
        print(json.dumps(report),flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage',choices=('submit','retro','nrt'),required=True)
    parser.add_argument('--domain',choices=tuple(DOMAINS))
    args = parser.parse_args()
    root = Path(os.environ['HYDRO_OPS_PROJECT_ROOT']).resolve()
    state = root/'nwm/status'/CAMPAIGN
    if args.stage == 'submit':
        submit(root,state)
    else:
        if args.domain is None:
            parser.error('Domain required')
        execute(root,state,args.domain,args.stage)


if __name__ == '__main__':
    main()
